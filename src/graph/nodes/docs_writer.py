"""Phase 5b — Living Docs Writer with Human Approval Gate.

Critical rule: never write directly to the repository, never auto-merge. The
node only opens a draft PR; a human has to approve it on GitHub. This breaks
the hallucination feedback loop that would otherwise occur if an LLM-written
explanation got indexed immediately and then retrieved as "evidence" for a
future query, reinforcing whatever it got wrong.

The flywheel closes in two possible ways, both implemented here:
  - GitHub webhook (`on_pr_merged`, wired into src/api/main.py) — production path.
  - `check_and_process_merged_prs` polling fallback — lets the flywheel be
    exercised/tested without standing up a public webhook endpoint.
Only once a PR is confirmed merged does its text get embedded into
`{repo_id}_adr_rfcs`, at which point it's real, human-validated evidence.
"""
import re
from datetime import datetime, timezone
from typing import Optional

from github import Github, GithubException

from src.config.settings import get_settings
from src.db import postgres
from src.graph.state import ArchaeologyState

LABELS = ["ai-generated", "archaeology-agent", "needs-review"]
LABEL_COLORS = {"ai-generated": "8A2BE2", "archaeology-agent": "1E90FF", "needs-review": "FFD700"}

# (leading_prefix, closing_suffix, per_line_prefix) — a leading comment block
# above the definition is used for every language rather than an in-body
# docstring: it's syntactically safe to insert via pure text (no AST-aware
# body edit needed) while still being idiomatic per language.
COMMENT_STYLE = {
    "python": ("", "", "# "),
    "javascript": ("/**\n", " */\n", " * "),
    "typescript": ("/**\n", " */\n", " * "),
    "java": ("/**\n", " */\n", " * "),
    "go": ("", "", "// "),
    "rust": ("", "", "/// "),
}


def _format_comment(language: str, answer: str) -> str:
    prefix, suffix, line_prefix = COMMENT_STYLE.get(language, ("", "", "# "))
    body_lines = [f"{line_prefix}{line}" for line in answer.strip().splitlines()]
    header = f"{line_prefix}[archaeology-agent] Historical context (AI-generated, pending human review):"
    return prefix + "\n".join([header, *body_lines]) + ("\n" + suffix if suffix else "\n")


def _get_github_client() -> Github:
    settings = get_settings()
    if not settings.github_token:
        raise RuntimeError(
            "GITHUB_TOKEN is required to open docs PRs (needs repo write scope) — read-only/unauthenticated "
            "access can't create branches or pull requests."
        )
    return Github(settings.github_token)


def _ensure_labels(repo) -> None:
    existing = {l.name for l in repo.get_labels()}
    for name in LABELS:
        if name not in existing:
            try:
                repo.create_label(name=name, color=LABEL_COLORS[name])
            except GithubException:
                pass  # created concurrently or already exists — non-fatal


def docs_writer_node(state: ArchaeologyState) -> dict:
    repo_id = state["repo_id"]
    chunk_id = state.get("target_chunk_id")
    answer = state.get("answer")
    if not chunk_id or not answer:
        return {"draft_pr_url": None}

    session_factory = postgres.get_session_factory()
    with session_factory() as session:
        chunk = (
            session.query(postgres.CodeChunkRecord)
            .filter_by(repo_id=repo_id, chunk_id=chunk_id)
            .one_or_none()
        )
    if not chunk:
        return {"draft_pr_url": None}

    gh = _get_github_client()
    repo = gh.get_repo(repo_id)
    default_branch = repo.default_branch

    file_content = repo.get_contents(chunk.file_path, ref=default_branch)
    original_text = file_content.decoded_content.decode("utf-8")
    lines = original_text.splitlines(keepends=True)

    comment_block = _format_comment(chunk.language, answer)
    insertion_index = chunk.start_line - 1  # insert directly above the definition line
    new_lines = lines[:insertion_index] + [comment_block] + lines[insertion_index:]
    new_content = "".join(new_lines)

    branch_name = f"archaeology-agent/docs-{re.sub(r'[^a-zA-Z0-9]', '-', chunk_id)}-{int(datetime.now(timezone.utc).timestamp())}"
    base_sha = repo.get_branch(default_branch).commit.sha
    repo.create_git_ref(ref=f"refs/heads/{branch_name}", sha=base_sha)

    repo.update_file(
        path=chunk.file_path,
        message=f"docs: add archaeology-agent context for {chunk.function_name or chunk.class_name or chunk.file_path}",
        content=new_content,
        sha=file_content.sha,
        branch=branch_name,
    )

    pr = repo.create_pull(
        title=f"[archaeology-agent] Add historical context to {chunk.function_name or chunk.file_path}",
        body=(
            f"Auto-generated by the Code Archaeology Agent in response to the query:\n\n> {state['query']}\n\n"
            f"**This PR is not auto-mergeable and must be reviewed by a human.** If the explanation below is "
            f"inaccurate, edit it before merging — only the merged (human-approved) text gets indexed for "
            f"future queries.\n\n---\n\n{answer}"
        ),
        base=default_branch,
        head=branch_name,
    )
    _ensure_labels(repo)
    pr.add_to_labels(*LABELS)

    with session_factory() as session:
        session.add(
            postgres.PendingDocPR(repo_id=repo_id, pr_number=pr.number, chunk_id=chunk_id, proposed_text=answer)
        )
        session.commit()

    return {"draft_pr_url": pr.html_url}


def on_pr_merged(repo_id: str, pr_number: int) -> bool:
    """Called by the GitHub webhook handler (src/api/main.py) when a tracked
    docs PR is merged. Ingests the now human-validated text into adr_rfcs.
    """
    from src.ingestion.embedding_agent import embed_text
    from src.db import chroma

    session_factory = postgres.get_session_factory()
    with session_factory() as session:
        row = (
            session.query(postgres.PendingDocPR)
            .filter_by(repo_id=repo_id, pr_number=pr_number, merged=False)
            .one_or_none()
        )
        if not row:
            return False
        row.merged = True
        session.commit()

        embedding = embed_text([row.proposed_text])[0]
        chroma.upsert(
            repo_id,
            "adr_rfcs",
            [f"docswriter-{pr_number}"],
            [embedding],
            [row.proposed_text],
            [
                {
                    "repo_id": repo_id,
                    "doc_type": "human_approved_explanation",
                    "source_id": f"pr-{pr_number}",
                    "file_path": "",
                    "timestamp": datetime.now(timezone.utc).isoformat(),
                    "author": "archaeology-agent",
                    "language": "",
                }
            ],
        )
        row.ingested = True
        session.commit()
    return True


def check_and_process_merged_prs(repo_id: str) -> int:
    """Polling fallback for environments without a reachable webhook endpoint:
    ask GitHub directly whether any tracked PR has been merged since we last checked.
    """
    gh = _get_github_client()
    repo = gh.get_repo(repo_id)

    session_factory = postgres.get_session_factory()
    with session_factory() as session:
        pending = session.query(postgres.PendingDocPR).filter_by(repo_id=repo_id, merged=False).all()
        pr_numbers = [p.pr_number for p in pending]

    processed = 0
    for pr_number in pr_numbers:
        pr = repo.get_pull(pr_number)
        if pr.merged:
            if on_pr_merged(repo_id, pr_number):
                processed += 1
    return processed
