"""Phase 4d — Provenance Classifier node.

Critical rule: seven classes, not a binary dead-code check. Missing
provenance most often means hotfix or legacy migration, not dead code —
jumping straight to "dead code" on sparse data is the wrong conclusion and
this node exists specifically to prevent that.

This is a reasoning task, not a lookup: the LLM (GPT-4o) is given the code
text, the shape of the provenance chain (which edges exist/are missing), and
the associated commit messages, plus the seven classes' signal patterns as
context — but the classification itself requires weighing ambiguous, partial
evidence, which is exactly what a heuristic classifier is bad at and an LLM
is good at.
"""
from typing import Optional

from langchain_core.prompts import ChatPromptTemplate
from pydantic import BaseModel, Field

from src.db import postgres
from src.graph.nodes.retrieval import find_target_chunk_via_chroma
from src.graph.state import ArchaeologyState, ProvenanceClass
from src.llm.llm_factory import get_llm

SIGNAL_PATTERNS = """
1. well_documented — Full chain: function -> commit -> PR -> issue, and the PR has a rich description.
2. legacy_migration — Old commits, no linked issues, commit message says "migrate" or "port".
3. hotfix — Commit message starts with "fix"/"hotfix"/"urgent". No PR. Committed directly to main.
4. experimental_prototype — Branch/commit references "experiment"/"spike"/"poc". Never linked to a formal issue.
5. generated_code — File path contains "generated"/"autogenerated"/"proto". Commit message is "regenerate" or similar.
6. third_party_import — File was added in a single large commit. Author email is external. No subsequent modifications.
7. orphaned — No linked PR. No linked issue. Commit message is one word or generic. No subsequent references. True dead code.
""".strip()

SYSTEM_PROMPT = f"""You are a provenance classifier for a code archaeology system. Given a code \
chunk, its provenance chain (which edges exist and which are missing), and associated commit \
messages, classify it into exactly ONE of these seven classes:

{SIGNAL_PATTERNS}

Missing provenance data (no linked PR, no linked issue) is common and does NOT by itself mean \
"orphaned" — it much more often means "hotfix" or "legacy_migration". Only classify as "orphaned" \
when the evidence actively supports it (generic/trivial commit message AND no subsequent \
references AND no PR/issue), not merely because data is sparse.

Respond with the class, a confidence between 0 and 1, and a one-sentence reasoning."""


class ProvenanceClassification(BaseModel):
    provenance_class: ProvenanceClass = Field(description="Exactly one of the seven defined classes")
    confidence: float = Field(ge=0.0, le=1.0)
    reasoning: str


def _gather_evidence(repo_id: str, chunk_id: str, state: ArchaeologyState) -> str:
    session_factory = postgres.get_session_factory()
    with session_factory() as session:
        chunk = (
            session.query(postgres.CodeChunkRecord)
            .filter_by(repo_id=repo_id, chunk_id=chunk_id)
            .one_or_none()
        )
        commit_shas = set()
        for chain in state.get("neo4j_results") or []:
            if chain.introduced_by_sha:
                commit_shas.add(chain.introduced_by_sha)
            if chain.last_modified_by_sha:
                commit_shas.add(chain.last_modified_by_sha)
        if chunk and chunk.last_modified_sha:
            commit_shas.add(chunk.last_modified_sha)

        commits = (
            session.query(postgres.Commit)
            .filter(postgres.Commit.repo_id == repo_id, postgres.Commit.sha.in_(commit_shas))
            .all()
            if commit_shas
            else []
        )

    chain = (state.get("neo4j_results") or [None])[0]
    evidence = [
        f"File path: {chunk.file_path if chunk else 'unknown'}",
        f"Function/class name: {(chunk.function_name or chunk.class_name) if chunk else 'unknown'}",
        "",
        "Code:",
        (chunk.chunk_text[:3000] if chunk else "(chunk text unavailable)"),
        "",
        "Provenance chain:",
        f"  introduced_by: {chain.introduced_by_sha if chain else 'MISSING'}",
        f"  last_modified_by: {chain.last_modified_by_sha if chain else 'MISSING'}",
        f"  linked PR: {chain.pr_number if chain else 'MISSING'}",
        f"  linked issue: {chain.issue_number if chain else 'MISSING'}",
        "",
        "Associated commits:",
    ]
    for c in commits:
        evidence.append(f"  - {c.sha[:10]} by {c.author_email}: {(c.message or '').strip()[:200]}")
    if not commits:
        evidence.append("  (none found)")

    return "\n".join(evidence)


def provenance_classifier_node(state: ArchaeologyState) -> dict:
    repo_id = state["repo_id"]
    target_chunk_id = state.get("target_chunk_id")
    if not target_chunk_id:
        target_chunk_id = find_target_chunk_via_chroma(repo_id, state["query"])
    if not target_chunk_id:
        # No resolvable function at all (e.g. a purely structural/"when" query with no code
        # target) — provenance classification doesn't apply; default to the most conservative class.
        return {"provenance_class": "orphaned", "provenance_confidence": 0.0}

    evidence = _gather_evidence(repo_id, target_chunk_id, state)

    prompt = ChatPromptTemplate.from_messages(
        [("system", SYSTEM_PROMPT), ("human", "{evidence}")]
    )
    chain = prompt | get_llm(purpose="default", temperature=0).with_structured_output(ProvenanceClassification)
    result: ProvenanceClassification = chain.invoke({"evidence": evidence})

    return {
        "provenance_class": result.provenance_class,
        "provenance_confidence": result.confidence,
        "target_chunk_id": target_chunk_id,
    }
